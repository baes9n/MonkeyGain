"""Install a per-user desktop launcher; does not require root or copy source."""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import os
from pathlib import Path
import shlex
import shutil
import sys

APP_ID = 'io.github.baes9n.MonkeyGain'
ICON_SIZES = (512, 256, 128, 64, 48, 32)
LEGACY_ICON_SHA256 = '283d669f1e4d8d6d4a66e1d6e84e3acaa52f87d1483a2206f580c9c48bbf16cd'


@dataclass(frozen=True)
class DesktopPaths:
    launcher: Path
    entry: Path
    icon: Path


def destination_paths(home: Path | None = None, data_home: Path | None = None) -> DesktopPaths:
    home = (home or Path.home()).expanduser()
    data_home = data_home or Path(os.environ.get('XDG_DATA_HOME') or home / '.local/share')
    return DesktopPaths(
        launcher=home / '.local/bin/monkeygain',
        entry=data_home / 'applications' / f'{APP_ID}.desktop',
        icon=data_home / 'icons/hicolor/256x256/apps' / f'{APP_ID}.png',
    )


def installed_icons(paths: DesktopPaths) -> tuple[Path, ...]:
    """Return icon theme paths for all bundled PNG sizes."""
    data_home = paths.entry.parent.parent
    return tuple(data_home / 'icons/hicolor' / f'{size}x{size}' / 'apps' / f'{APP_ID}.png'
                 for size in ICON_SIZES)


def old_svg_icon(paths: DesktopPaths) -> Path:
    """The location of the pre-v0.3.5 MonkeyGain SVG icon."""
    return paths.entry.parent.parent / 'icons/hicolor/scalable/apps' / f'{APP_ID}.svg'


def remove_old_icon(paths: DesktopPaths) -> None:
    """Remove only the exact SVG icon shipped in older MonkeyGain versions."""
    old = old_svg_icon(paths)
    if old.is_file() and not old.is_symlink():
        digest = hashlib.sha256(old.read_bytes()).hexdigest()
        if digest == LEGACY_ICON_SHA256:
            old.unlink()


def desktop_quote(value: str) -> str:
    """Quote a desktop-entry argument according to the Desktop Entry Exec syntax."""
    # Quote the entire executable path: even apostrophes are plain characters in
    # .desktop syntax, unlike in a POSIX shell. Escape reserved characters.
    if any(char in value for char in ' \t\n"\\`$'):
        escaped = value.replace('\\', '\\\\').replace('"', '\\"').replace('`', '\\`').replace('$', '\\$')
        return f'"{escaped}"'
    return value


def launcher_contents(source_dir: Path, python: str) -> str:
    """Source stays in the Git checkout and all arguments remain individually quoted."""
    root = (source_dir / 'run.py').resolve()
    return ('#!/bin/sh\n'
            '# Generated by MonkeyGain; reinstall after moving the source folder.\n'
            f'exec {shlex.quote(python)} {shlex.quote(str(root))} "$@"\n')


def desktop_contents(paths: DesktopPaths) -> str:
    return (f'[Desktop Entry]\n'
            f'Type=Application\n'
            f'Name=MonkeyGain\n'
            f'GenericName=ReplayGain Analyzer\n'
            f'Comment=Analyze music loudness and write ReplayGain tags\n'
            f'Exec={desktop_quote(str(paths.launcher))} %F\n'
            f'Icon={APP_ID}\n'
            f'Terminal=false\n'
            f'Categories=AudioVideo;Audio;Utility;\n'
            f'MimeType=audio/flac;audio/x-flac;audio/mpeg;audio/mp4;audio/ogg;audio/x-wav;audio/x-aiff;audio/x-opus+ogg;\n'
            f'Keywords=ReplayGain;Loudness;Audio;Music;\n'
            f'StartupNotify=true\n'
            f'X-GNOME-UsesNotifications=true\n')


def install(source_dir: Path, paths: DesktopPaths | None = None, python: str | None = None) -> DesktopPaths:
    paths = paths or destination_paths()
    source_dir = source_dir.resolve()
    if not (source_dir / 'run.py').is_file():
        raise FileNotFoundError('MonkeyGain source files were not found.')
    for size in ICON_SIZES:
        if not (source_dir / 'assets/icons' / f'{size}.png').is_file():
            raise FileNotFoundError(f'MonkeyGain icon for {size}px was not found.')
    python = python or sys.executable
    if not Path(python).is_file():
        raise FileNotFoundError(f'Python executable not found: {python}')
    icons = installed_icons(paths)
    for dest in (paths.launcher, paths.entry, *icons):
        if dest.is_symlink():
            raise FileExistsError(f'Refusing to overwrite a symbolic link: {dest}')
        if dest == paths.launcher and dest.is_file():
            if 'Generated by MonkeyGain' not in dest.read_text(encoding='utf-8'):
                raise FileExistsError(f'An unrelated launcher already exists: {dest}')
        if dest == paths.entry and dest.is_file():
            if 'Name=MonkeyGain\n' not in dest.read_text(encoding='utf-8'):
                raise FileExistsError(f'An unrelated desktop entry already exists: {dest}')
        dest.parent.mkdir(parents=True, exist_ok=True)
    paths.launcher.write_text(launcher_contents(source_dir, python), encoding='utf-8')
    paths.launcher.chmod(0o755)
    for size, dest in zip(ICON_SIZES, icons):
        shutil.copyfile(source_dir / 'assets/icons' / f'{size}.png', dest)
    paths.entry.write_text(desktop_contents(paths), encoding='utf-8')
    remove_old_icon(paths)
    return paths


def uninstall(paths: DesktopPaths | None = None) -> list[Path]:
    """Remove only generated files, never the Git checkout or user config."""
    paths = paths or destination_paths()
    deleted: list[Path] = []
    for file in (paths.entry, *installed_icons(paths), paths.launcher):
        if file.is_symlink():
            # Avoid following unexpected links outside the installation locations.
            continue
        if file.exists():
            if file == paths.launcher and 'Generated by MonkeyGain' not in file.read_text(encoding='utf-8'):
                continue
            if file == paths.entry and 'Name=MonkeyGain\n' not in file.read_text(encoding='utf-8'):
                continue
            file.unlink()
            deleted.append(file)
    return deleted
